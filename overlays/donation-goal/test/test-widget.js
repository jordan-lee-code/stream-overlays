/* Headless test for the donation goal. Runs the real widget/widget.js against a small mock of the
   page and StreamElements, with a clock the test controls. */
const env = require("./mock")(require("path").join(__dirname, ".."));
const { ok, section, load, reload, boss, chat, button, settled, wait, E, storeData, audioLog } = env;
const tip = (n, name) => env.ev("tip-latest", { amount: n, name: name === undefined ? "Alice" : name });
const amount = () => E("dg-amount").hidden ? "" : E("dg-amount").textContent;
const pct = () => E("dg-percent").hidden ? "" : E("dg-percent").textContent;
const fill = () => E("dg-fill").style.width;
const status = () => E("dg-status").hidden ? "" : E("dg-status").textContent;
const latest = () => E("dg-latest").hidden ? "" : E("dg-latest").textContent;
const reached = () => E("dg-app").classList.contains("reached");
const skip = async ms => { env.fake += ms; await wait(700); };

(async () => {
  section("what it shows");
  await load();
  ok(amount() === "$0 of $100" && pct() === "0%" && fill() === "0%", "it starts empty (" + amount() + ", " + pct() + ", " + fill() + ")");
  ok(E("dg-title").textContent === "Donation goal" && !E("dg-title").hidden, "with its title");
  ok(status() === "" && latest() === "" && !reached(), "and no message, no donor and no celebration");
  tip(25, "Alice");
  ok(amount() === "$25 of $100" && pct() === "25%" && fill() === "25%", "a tip fills the bar (" + amount() + ", " + pct() + ", " + fill() + ")");
  ok(latest() === "Latest: Alice gave $25", "and shows who gave it (" + latest() + ")");
  tip(12.5, "Bea");
  ok(amount() === "$37.50 of $100" && pct() === "37%" && fill() === "37.5%" && latest() === "Latest: Bea gave $12.50", "cents show when there are some, and the percentage is whole (" + amount() + ", " + pct() + ")");
  await load(); tip(0.1); tip(0.2);
  ok(amount() === "$0.30 of $100", "small amounts add up exactly, with no rounding drift (" + amount() + ")");
  await load(); tip("5.00"); ok(amount() === "$5 of $100", "a tip that arrives as text counts (" + amount() + ")");
  tip(33.33); tip(33.33); tip(33.33); ok(amount() === "$104.99 of $100", "and three thirds of a hundred do not become a hundred (" + amount() + ")");

  section("what does not count");
  await load();
  tip(0); tip(-5); tip("lots"); tip(null); tip(undefined); tip(NaN); tip(Infinity); tip(1e12); tip({}); tip([]);
  ok(amount() === "$0 of $100" && latest() === "", "empty, negative, odd and impossibly large tips count for nothing");
  env.ev("cheer-latest", { amount: 5000, name: "Cara" }); env.ev("cheer-latest", { amount: 1, name: "Cara" });
  env.ev("subscriber-latest", { amount: 1, name: "Dan" }); env.ev("follower-latest", { name: "Eli" }); env.ev("raid-latest", { name: "Fay", amount: 50 });
  ok(amount() === "$0 of $100" && latest() === "", "bits, subs, follows and raids are for the other overlays, and never count here");
  await load({ minTip: 5 }); tip(4.99, "Low"); tip(5, "Ok");
  ok(amount() === "$5 of $100" && latest() === "Latest: Ok gave $5", "a smallest tip can be set (" + amount() + ")");

  section("who gave it");
  await load();
  tip(5, ""); ok(latest() === "Latest: Anonymous gave $5", "a blank name is Anonymous (" + latest() + ")");
  tip(5, "anonymous"); tip(5, "AnAnonymousGifter"); tip(5, "  "); ok(latest() === "Latest: Anonymous gave $5", "so are the names StreamElements uses for one");
  env.ev("tip-latest", { amount: 5, username: "ViaUsername" }); ok(latest() === "Latest: ViaUsername gave $5", "a name can come as a username");
  await load({ anonymousName: "A kind person" }); tip(5, ""); ok(latest() === "Latest: A kind person gave $5", "and Anonymous is a setting");

  section("reaching the goal");
  await load({ goal: 100 });
  tip(99); ok(!reached() && status() === "", "just short of it is not reaching it");
  tip(1);
  ok(reached() && status() === "Goal reached! Thank you" && pct() === "100%" && fill() === "100%", "the goal is reached at exactly the goal (" + status() + ")");
  tip(20);
  ok(amount() === "$120 of $100" && pct() === "120%" && fill() === "100%" && reached(), "more still counts, the percentage goes past 100 and the bar stays full (" + amount() + ", " + pct() + ")");
  await load({ goal: 100 }); tip(250); ok(amount() === "$250 of $100" && pct() === "250%", "one big tip can pass it by a long way");
  await load({ goal: 100, startAmount: 100 }); ok(reached(), "starting at or past the goal counts as reached");

  section("a goal that stretches");
  await load({ goal: 100, whenReached: "stretch", stretchBy: 50 });
  tip(60); ok(amount() === "$60 of $100" && !reached(), "it behaves as normal until the goal is reached");
  tip(40);
  ok(amount() === "$100 of $150" && pct() === "66%" && fill() !== "100%", "then the goal goes up and the bar carries on (" + amount() + ", " + fill() + ")");
  ok(reached() && status() === "Goal reached! Thank you", "with a message for a while");
  await skip(5000); ok(reached(), "which is still there after five seconds");
  await skip(6000); ok(!reached() && status() === "", "and gone after ten");
  tip(50); ok(amount() === "$150 of $200", "the new goal can be reached too (" + amount() + ")");
  await load({ goal: 100, whenReached: "stretch", stretchBy: 50 }); tip(400);
  ok(amount() === "$400 of $450", "one big tip raises the goal as many times as it takes (" + amount() + ")");
  await load({ goal: 100, whenReached: "stretch", stretchBy: 0.5 }); tip(100);
  ok(amount() === "$100 of $100.50", "by a small step too (" + amount() + ")");
  await load({ goal: 100, whenReached: "stretch", stretchBy: 50, reachedText: "Done! Next: {goal}" }); tip(100);
  ok(status() === "Done! Next: $150", "and the message can say what the new goal is (" + status() + ")");
  await load({ goal: 100, whenReached: "stretch", stretchBy: 50 }); tip(100); await env.reload(); ok(reached(), "the message survives a refresh while it is still due");
  await skip(11000); ok(!reached(), "and a refresh after its time does not bring it back");

  section("chat commands");
  await load();
  chat("!donation add 10", { nick: "viewer" }); ok(amount() === "$0 of $100", "a viewer cannot change it");
  chat("!donation add 10", { mod: true }); ok(amount() === "$10 of $100" && latest() === "", "a moderator can add to it, with nobody credited (" + amount() + ")");
  chat("!donation add -4", { mod: true }); ok(amount() === "$6 of $100", "or take away (" + amount() + ")");
  chat("!donation add -100", { mod: true }); ok(amount() === "$0 of $100", "but never below nothing (" + amount() + ")");
  chat("!donation set 42.50", { mod: true }); ok(amount() === "$42.50 of $100", "set puts the total right (" + amount() + ")");
  chat("!donation goal 200", { mod: true }); ok(amount() === "$42.50 of $200", "goal changes the goal (" + amount() + ")");
  for (const form of [["$5", "$5"], ["5,50", "$5.50"], ["+3", "$3"], ["  7  ", "$7"], ["\u00a312.5", "$12.50"], ["\u20ac4", "$4"], ["5 kr", "$5"], ["5.5", "$5.50"]]) {
    boss("!donation set 0"); boss("!donation add " + form[0]);
    ok(amount() === form[1] + " of $200", "an amount can be written as " + JSON.stringify(form[0]) + " (" + amount() + ")");
  }
  boss("!donation set 0");
  const before = amount();
  for (const bad of ["add", "add lots", "add 1,250", "add 1.234", "add --5", "set -5", "set", "goal 0", "goal -10", "goal lots", "add 1e3", "nonsense 5"]) boss("!donation " + bad);
  ok(amount() === before, "anything unreadable changes nothing and says nothing (" + amount() + ")");
  tip(80); boss("!donation reset");
  ok(amount() === "$0 of $100" && latest() === "", "reset starts again, with the goal in the settings and no donor (" + amount() + ")");
  await load({ startAmount: 20 }); tip(30); boss("!donation goal 500"); boss("!donation reset");
  ok(amount() === "$20 of $100" && latest() === "", "back to the starting amount and the goal in the settings (" + amount() + ")");
  chat("!donation", { nick: "viewer" }); ok(E("dg-title").classList.contains("pop"), "the bare command only draws the eye to it");
  await load({ whoCanManage: "broadcaster" }); chat("!donation add 5", { mod: true }); ok(amount() === "$0 of $100", "unless only the broadcaster is allowed");
  boss("!donation add 5"); ok(amount() === "$5 of $100", "who always can");
  chat("!donationx add 5", { mod: true }); boss("!donations add 5"); ok(amount() === "$5 of $100", "whole words only: !donationx is not the command");
  await load({ command: "!give" }); boss("!donation add 5"); ok(amount() === "$0 of $100", "the command word is a setting");
  boss("!give add 5"); ok(amount() === "$5 of $100", "and the new one works");
  await load({ goal: 100, whenReached: "stretch", stretchBy: 50 }); boss("!donation add 100");
  ok(amount() === "$100 of $150" && reached(), "adding by hand reaches a stretching goal too");
  await load(); boss("!donation add 100"); ok(reached(), "and a staying one");
  boss("!donation set 10"); ok(!reached() && amount() === "$10 of $100", "and taking it back below the goal clears it (" + amount() + ")");

  section("keeping it between refreshes");
  await load();
  tip(30, "Alice"); await wait(10); await reload();
  ok(amount() === "$30 of $100" && latest() === "Latest: Alice gave $30", "the total and the latest donor survive a refresh (" + amount() + ")");
  boss("!donation goal 300"); await reload();
  ok(amount() === "$30 of $300", "so does a goal set from chat (" + amount() + ")");
  await load({}, true);
  ok(amount() === "$30 of $300", "a goal set from chat stays while the setting is left alone (" + amount() + ")");
  await load({ goal: 150 }, true);
  ok(amount() === "$30 of $150", "but a goal changed in the settings wins over the saved one (" + amount() + ")");
  await load({ goal: 150, startAmount: 50 }, true);
  ok(amount() === "$30 of $150", "and the starting amount is used only the first time (" + amount() + ")");
  await load({ startAmount: 50 }); ok(amount() === "$50 of $100", "which starts from it");
  await load();
  storeData.donations_v1 = "garbage"; await reload(); ok(amount() === "$0 of $100", "a save that is not an object starts afresh");
  storeData.donations_v1 = { raised: "x", goal: -5, goalSetting: 10000, latest: { name: 5, cents: "a" }, bannerUntil: "soon" }; await reload();
  ok(amount() === "$0 of $100" && latest() === "", "a damaged one is read as far as it can be (" + amount() + ")");
  storeData.donations_v1 = { raised: 2500, goal: 0, goalSetting: 10000 }; await reload();
  ok(amount() === "$25 of $100", "a missing goal falls back to the setting and keeps the money (" + amount() + ")");
  storeData.donations_v1 = { raised: -50, goal: 1e18, goalSetting: 10000, latest: { name: "Zed", cents: -3 } }; await reload();
  ok(/^\$0 of \$/.test(amount()) && latest() === "", "negative and absurd values are held in range (" + amount() + ")");
  storeData.donations_v1 = null; await reload(); ok(amount() === "$0 of $100", "and nothing at all is fine");

  section("how money is written");
  await load({ goal: 1000 }); tip(1250.5);
  ok(amount() === "$1,250.50 of $1,000", "thousands are separated (" + amount() + ")");
  await load({ symbol: "€", symbolAfter: true }); tip(5);
  ok(amount() === "5€ of 100€" && latest() === "Latest: Alice gave 5€", "a lone sign can follow the amount (" + amount() + ")");
  await load({ symbol: "kr", symbolAfter: true }); tip(5); ok(amount() === "5\u00a0kr of 100\u00a0kr", "a word follows it with a space that does not break the line (" + amount() + ")");
  await load({ decimalComma: true, goal: 1000 }); tip(1250.5);
  ok(amount() === "$1.250,50 of $1.000", "a comma decimal makes the thousands use a point (" + amount() + ")");
  await load({ symbol: "" }); tip(5); ok(amount() === "5 of 100", "a blank symbol shows none (" + amount() + ")");
  await load({ decimals: "always" }); tip(5); ok(amount() === "$5.00 of $100.00", "cents can always show (" + amount() + ")");
  await load({ decimals: "none" }); tip(5.4); ok(amount() === "$5 of $100", "or never (" + amount() + ")");
  tip(0.1); ok(amount() === "$6 of $100", "rounded as a person would (" + amount() + ")");
  await load({ goal: 99.99 }); ok(amount() === "$0 of $99.99", "a goal with cents shows them (" + amount() + ")");
  await load({ goal: 0 }); ok(amount() === "$0 of $100", "a goal of nothing is the usual one (" + amount() + ")");
  await load({ goal: -20 }); ok(amount() === "$0 of $100", "and so is a negative one (" + amount() + ")");
  await load({ goal: "lots" }); ok(amount() === "$0 of $100", "and a goal that is not a number is the usual one");

  section("the wording");
  await load({ amountText: "{raised} / {goal} ({percent})", percentText: "{percent} done" }); tip(25);
  ok(amount() === "$25 / $100 (25)" && pct() === "25 done", "every sentence is a setting, with tokens (" + amount() + ", " + pct() + ")");
  await load({ amountText: "" }); ok(amount() === "", "a blank amount line hides it");
  await load({ percentText: "" }); ok(pct() === "", "and so does a blank percentage");
  await load({ reachedText: "" }); tip(100); ok(status() === "" && reached(), "a blank message shows no message, though it is still reached");
  await load({ latestText: "{name}: {amount}" }); tip(5, "Zed"); ok(latest() === "Zed: $5", "the donor line can read as you like (" + latest() + ")");
  await load({ showLatest: false }); tip(5); ok(latest() === "", "or be left off");
  await load({ showPercent: false }); ok(pct() === "", "the percentage can be left off");
  await load({ showAmounts: false }); ok(amount() === "", "so can the amounts");
  await load({ title: "Help us get there" }); ok(E("dg-title").textContent === "Help us get there", "the title is a setting");
  await load({ title: "" }); ok(E("dg-title").hidden, "a blank title hides it");
  await load({ showTitle: false }); ok(E("dg-title").hidden, "or it can be switched off");
  await load({ title: "<b>x</b>" }); ok(E("dg-title").textContent === "<b>x</b>", "text is shown as typed, never as markup");
  await load(); tip(5, "<img src=x onerror=alert(1)>"); ok(latest() === "Latest: <img src=x onerror=alert(1)> gave $5", "including a donor's name");

  section("looks");
  await load({ textSize: 8, barHeight: 1.5, titleScale: 2 });
  const v = env.vars("dg-app");
  ok(v["--dg-size"] === "8cqw" && v["--dg-bar"] === "1.5em" && v["--dg-title"] === 2, "the sizes are settings");
  await load(); ok(env.vars("dg-app")["--w-bg"] === "rgba(0, 0, 0, 0.55)", "Soft black is the default");
  await load({ themePreset: "custom", radius: 10, borderWidth: 2, borderColor: "#FF0000", weight: 600, pad: 1, shadow: true, animate: false });
  const w = env.vars("dg-app");
  ok(w["--w-radius"] === "10px" && w["--w-border"] === "2px solid #FF0000" && w["--w-weight"] === 600 && w["--w-pad"] === 1 && w["--w-shadow"] !== "none", "the corner, outline, boldness, padding and shadow follow the settings");
  ok(E("dg-root").classList.contains("no-motion"), "and Animate off stops motion");
  await load(); tip(5); ok(E("dg-app").classList.contains("bump"), "a donation makes the amounts pop");
  await load({ animate: false }); E("dg-app").classList.remove("bump"); tip(5); ok(!E("dg-app").classList.contains("bump"), "unless Animate is off");
  await env.checkPresets("dg-app");

  section("sounds");
  await load({ soundTip: "data:audio/wav;base64,AA", soundTipVol: 40, soundReached: "data:audio/wav;base64,BB", soundReachedVol: 90 });
  audioLog.length = 0; tip(5); ok(audioLog.length === 1 && audioLog[0].src.endsWith("AA") && Math.abs(audioLog[0].volume - 0.4) < 1e-9, "a donation plays its sound at its volume");
  audioLog.length = 0; tip(95); ok(audioLog.length === 1 && audioLog[0].src.endsWith("BB") && Math.abs(audioLog[0].volume - 0.9) < 1e-9, "the donation that reaches the goal plays the goal sound instead, once");
  audioLog.length = 0; tip(5); ok(audioLog.length === 1 && audioLog[0].src.endsWith("AA"), "and a later one is back to the donation sound");
  audioLog.length = 0; tip(0); tip(-1); env.ev("cheer-latest", { amount: 500 }); ok(audioLog.length === 0, "a gift that does not count is silent");
  audioLog.length = 0; button("test_soundTip"); button("test_soundReached"); ok(audioLog.length === 2, "the Test buttons play");
  await load({ soundTip: "data:audio/wav;base64,AA", mute: true }); audioLog.length = 0; tip(5); ok(audioLog.length === 0, "mute silences everything");

  section("buttons");
  await load();
  button("btnDemo"); ok(amount() === "$5 of $100" && latest() === "Latest: Test donor gave $5", "the test donation adds five (" + amount() + ")");
  button("btnReset"); ok(amount() === "$0 of $100" && latest() === "", "and Start again empties it (" + amount() + ")");

  section("odd input never breaks it");
  await load();
  env.ev("message", {}); env.ev("message", { data: null }); env.ev("message", { data: { text: 5 } }); env.ev("message", { data: { text: "!donation add 5", badges: "x", tags: null } });
  env.ev("tip-latest", {}); env.ev("tip-latest", null); env.ev("nonsense", {}); env.ev("widget-button", { field: "nope" });
  ok(amount() === "$0 of $100", "empty, missing and wrongly typed events are ignored");
  tip(5); ok(amount() === "$5 of $100", "and it carries on afterwards");

  section("every setting is wired up");
  env.checkWired();
  env.checkNotice();
  env.finish();
})();
